using System.Text;
using NuStreamDocs.Building;
using NuStreamDocs.Common;
using NuStreamDocs.Theme.Material3;

namespace NuStreamDocs.ContentLoader.Schemas.Tests;

/// <summary>Tests for <see cref="AsyncApiContentLoader"/>, <see cref="AsyncApiPageBuilder"/>, and end-to-end <see cref="DocBuilder"/> integration.</summary>
public sealed class AsyncApiContentLoaderTests
{
    /// <summary>Shared route segment for AsyncAPI test cases.</summary>
    private const string EventsSegment = "events";

    /// <summary>Directory index filename generated by <see cref="DocBuilder"/>.</summary>
    private const string IndexFile = "index.html";

    /// <summary>Gets a sample AsyncAPI 3.0 JSON specification with channels and operations.</summary>
    private static ReadOnlySpan<byte> AsyncApi3Json => """
        {
          "asyncapi": "3.0.0",
          "info": {
            "title": "Order Events",
            "version": "1.2.0",
            "description": "Event stream for orders.",
            "contact": { "name": "Ops" }
          },
          "channels": {
            "orderCreated": {
              "address": "orders.created",
              "description": "Emitted when an order is created.",
              "messages": {}
            },
            "invalidChannel": "skip"
          },
          "operations": {
            "publishOrderCreated": {
              "action": "send",
              "summary": "Publishes order creation.",
              "description": "Secondary description skipped because summary came first.",
              "channel": {}
            },
            "receiveAudit": {
              "description": "Fallback operation description."
            },
            "invalidOp": 123
          },
          "servers": {}
        }
        """u8;

    /// <summary>Verifies constructor guards on <see cref="AsyncApiContentLoader"/>.</summary>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    public async Task Constructor_InvalidArguments_Throws()
    {
        await Assert.That(static () => new AsyncApiContentLoader(default(FilePath), EventsSegment)).Throws<ArgumentException>();
        await Assert.That(static () => new AsyncApiContentLoader(null!, EventsSegment, EventsSegment)).Throws<ArgumentNullException>();
        await Assert.That(static () => new AsyncApiContentLoader("{}"u8.ToArray(), " ", EventsSegment)).Throws<ArgumentException>();
    }

    /// <summary>Verifies AsyncAPI 3.0 inline JSON and AsyncAPI 2.6 YAML local files plus full <see cref="DocBuilder"/> site rendering.</summary>
    /// <param name="cancellationToken">Test cancellation token.</param>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    public async Task LoadAsync_AsyncApi2And3AndDocBuilder_EmitsReferencePages(CancellationToken cancellationToken)
    {
        var loader3 = new AsyncApiContentLoader(AsyncApi3Json.ToArray(), "fallback", "reference/events");
        var loaderName = Encoding.UTF8.GetString(loader3.Name);
        await Assert.That(loaderName).IsEqualTo("asyncapi");

        var pages3 = await loader3.LoadAsync(new(default), cancellationToken);
        await Assert.That(pages3).HasSingleItem();
        await Assert.That(pages3[0].RelativePath.Value).IsEqualTo("reference/events/order-events.md");

        var md3 = Encoding.UTF8.GetString(pages3[0].MarkdownBytes);
        await Assert.That(md3).Contains("**Version:** `1.2.0`");
        await Assert.That(md3).Contains("Event stream for orders.");
        await Assert.That(md3).Contains("| `orderCreated` | `orders.created` | `channel` | Emitted when an order is created. |");
        await Assert.That(md3).Contains("| `publishOrderCreated` | `send` | Publishes order creation. |");
        await Assert.That(md3).Contains("| `receiveAudit` | `send` | Fallback operation description. |");

        var dir = Directory.CreateTempSubdirectory("nstd-asyncapi-");
        try
        {
            var docsDir = Directory.CreateDirectory(Path.Combine(dir.FullName, "docs"));
            var outDir = Path.Combine(dir.FullName, "site");
            await File.WriteAllTextAsync(Path.Combine(docsDir.FullName, "index.md"), "# Home\n", cancellationToken);
            const string asyncApi2Yaml = "asyncapi: 2.6.0\nchannels:\n  user/signedup:\n    publish:\n      message: {}\n    subscribe:\n      message: {}\n";
            await File.WriteAllTextAsync(Path.Combine(docsDir.FullName, "events.yaml"), asyncApi2Yaml, cancellationToken);

            await new DocBuilder()
                .WithInput(docsDir.FullName)
                .WithOutput(outDir)
                .UseDirectoryUrls()
                .UseMaterial3Theme()
                .UseContentLoaders(
                    new AsyncApiContentLoader("events.yaml", EventsSegment),
                    new JsonSchemaContentLoader("{\"title\":\"Settings\"}"u8.ToArray(), "settings", "schemas"),
                    new GraphQlSchemaContentLoader("type Query { version: String! }"u8.ToArray(), "Graph", "graphql"))
                .BuildAsync(cancellationToken);

            var renderedEvents = await File.ReadAllTextAsync(Path.Combine(outDir, EventsSegment, EventsSegment, IndexFile), cancellationToken);
            await Assert.That(renderedEvents).Contains("publish, subscribe");
            await Assert.That(File.Exists(Path.Combine(outDir, "schemas", "settings", IndexFile))).IsTrue();
            await Assert.That(File.Exists(Path.Combine(outDir, "graphql", "graph", IndexFile))).IsTrue();
        }
        finally
        {
            dir.Delete(true);
        }
    }

    /// <summary>Verifies minimal object fallback and malformed root error handling in <see cref="AsyncApiPageBuilder"/>.</summary>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    public async Task Build_MinimalAndInvalidInputs_HandlesCleanly()
    {
        var minimal = AsyncApiPageBuilder.Build("{\"info\":\"notObject\",\"channels\":\"notObject\",\"operations\":\"notObject\"}"u8.ToArray(), EventsSegment, "Minimal Spec");
        await Assert.That(minimal[0].RelativePath.Value).IsEqualTo("events/minimal-spec.md");

        await Assert.That(static () => AsyncApiPageBuilder.Build([], EventsSegment, "e")).Throws<ContentLoaderException>();
        await Assert.That(static () => AsyncApiPageBuilder.Build("[]"u8.ToArray(), EventsSegment, "e")).Throws<ContentLoaderException>();
        await Assert.That(static () => AsyncApiPageBuilder.Build("{broken"u8.ToArray(), EventsSegment, "e")).Throws<ContentLoaderException>();
    }
}
